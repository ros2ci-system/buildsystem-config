"""
The package build job: build one ROS package as a package of the target.

It runs inside a job container and follows the agent's contract, as the
core workspace job does:

* parameters come from ``params.json`` in the job directory,
* the source tarball is an input, in the ``in`` subdirectory,
* everything written to the ``out`` subdirectory is kept: the packages
  under ``out/packages``, and ``out/results.json``, which lists them and
  says how every test went,
* the exit code is 0 for success, 75 for a problem outside the package
  (a network failure, a package mirror that is down), and anything else
  for a failure of the build or its tests.

The image decides the format: Debian packages where ``dpkg-buildpackage``
is installed, RPM packages where ``rpmbuild`` is. The steps are the same:

1. unpack the source tarball and find the package in it,
2. bring the system up to date,
3. fetch the rosdep rules, and keep a copy of what was fetched,
4. generate the packaging from package.xml,
5. install the build dependencies the packaging names,
6. build the source package and the binary packages, which also runs the
   package's tests,
7. collect the packages and the test results.

The packaging is generated by the tools each format has:

* Debian: dyndeb writes the ``debian`` directory. Build dependencies are
  resolved then; install-time dependencies during the build.
* RPM: bloom writes the spec file, from the templates of its dynamic RPM
  generator. The spec names no dependencies. bloom's RPM macros resolve
  them during the build, through rosdep.

Neither packaging lets a failing test stop the build, so the packages
exist either way. This job is what decides: failing tests fail the job.

Parameters:

``package``
    The name of the ROS package to build. Required.
``source``
    The name of the source tarball among the inputs. Default
    ``source.tar.gz``. It may hold one package or a repository of several.
``rosdistro``
    The ROS distribution. Default ``rolling``.
``rosdistro_url``
    The base URL of the rosdistro to resolve against: where its
    ``index-v4.yaml`` is.
``rosdep_rules``
    The rosdep rule files, as paths under ``rosdistro_url``.
``skip_keys``
    rosdep keys that are not to be resolved. RPM packages only so far.
``revision``
    Which build of this version this is. Default 1.
``test``
    Whether to run the package's tests. Default true.
"""

import glob
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tarfile
import time
import xml.etree.ElementTree as ElementTree

# What every job script needs is in the core workspace job, which is the
# older of the two.
from core_workspace import DEFAULT_ROSDISTRO_URL, DEFAULT_RULES
from core_workspace import EXIT_FAILED, EXIT_INFRASTRUCTURE, EXIT_OK
from core_workspace import Failure, IN_DIR, JOB_DIR, OUT_DIR
from core_workspace import read_junit, retry, run, section

WORK = '/ws'
SOURCE_DIR = os.path.join(WORK, 'source')
BUILD_DIR = os.path.join(WORK, 'build')
TEST_RESULTS_DIR = os.path.join(WORK, 'test_results')

# rosdep's own default places: for its list of rule files, and for the
# rules it fetched. Everything finds the rules there without any setting,
# which matters because the build runs the package's tests: they must not
# see settings made for rosdep.
ROSDEP_SOURCES_DIR = '/etc/ros/rosdep/sources.list.d'
ROSDEP_CACHE_DIR = os.path.expanduser('~/.ros/rosdep')


def sha256_of(path):
    digest = hashlib.sha256()
    with open(path, 'rb') as f:
        for block in iter(lambda: f.read(1 << 20), b''):
            digest.update(block)
    return digest.hexdigest()


def output_of(command):
    """The output of a command that only reports something, or ''."""
    try:
        return subprocess.run(command, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                              errors='replace').stdout.strip()
    except OSError:
        return ''


class Job:
    """What is the same for every package format."""

    format = None

    def __init__(self, params):
        self.package = params.get('package', '')
        self.source = params.get('source', 'source.tar.gz')
        self.rosdistro = params.get('rosdistro', 'rolling')
        self.rosdistro_url = params.get('rosdistro_url', DEFAULT_ROSDISTRO_URL).rstrip('/')
        self.rules = params.get('rosdep_rules', DEFAULT_RULES)
        self.skip_keys = params.get('skip_keys', [])
        self.revision = str(params.get('revision', 1))
        self.test = params.get('test', True)
        if not re.match(r'^[a-z][a-z0-9_]*$', self.package):
            raise Failure('bad_parameters', '"package" must be the name of a ROS package', EXIT_FAILED)
        if not re.match(r'^[a-z][a-z0-9_]*$', self.rosdistro):
            raise Failure('bad_parameters', '%s is not a valid rosdistro' % self.rosdistro, EXIT_FAILED)
        if not re.match(r'^[1-9][0-9]*$', self.revision):
            raise Failure('bad_parameters', '"revision" must be a whole number, 1 or more', EXIT_FAILED)
        if not re.match(r'^[A-Za-z0-9][A-Za-z0-9+._-]*$', self.source):
            raise Failure('bad_parameters', '"source" must be the name of an input', EXIT_FAILED)
        for key in self.skip_keys:
            if not re.match(r'^[A-Za-z0-9][A-Za-z0-9+._-]*$', key):
                raise Failure('bad_parameters', '%r is not a rosdep key' % key, EXIT_FAILED)

        self.version = None
        self.package_name = 'ros-%s-%s' % (self.rosdistro, self.package.replace('_', '-'))
        # The package's source, in a directory named <package name>-<version>.
        self.tree = None
        self.stages = []
        self.artifacts = []
        self.tests = None
        self.tools = {}
        self.rosdep_cache = []
        self.warnings = []

        # rosdep is told where the rosdistro is, and nothing else.
        self.env = dict(os.environ)
        self.env.update({
            'ROS_DISTRO': self.rosdistro,
            'ROS_VERSION': '2',
            'ROS_PYTHON_VERSION': '3',
            'ROSDISTRO_INDEX_URL': self.rosdistro_url + '/index-v4.yaml',
            'DEBIAN_FRONTEND': 'noninteractive',
            'PYTHONUNBUFFERED': '1',
        })

    def build_env(self):
        """
        The environment of the build itself.

        What the image has, plus where the rosdistro is, which the tools
        that resolve dependencies during the build need.
        """
        env = dict(os.environ)
        env.update({
            'ROSDISTRO_INDEX_URL': self.env['ROSDISTRO_INDEX_URL'],
            'DEBIAN_FRONTEND': 'noninteractive',
            'PYTHONUNBUFFERED': '1',
        })
        return env

    def stage(self, name, function):
        section(name)
        started = time.time()
        try:
            function()
        except Failure:
            self.stages.append({'name': name, 'seconds': round(time.time() - started, 1), 'ok': False})
            raise
        self.stages.append({'name': name, 'seconds': round(time.time() - started, 1), 'ok': True})

    # -- steps -------------------------------------------------------

    def unpack(self):
        archive = os.path.join(IN_DIR, self.source)
        if not os.path.isfile(archive):
            raise Failure('bad_parameters', 'there is no input named %s' % self.source, EXIT_FAILED)
        os.makedirs(SOURCE_DIR)
        try:
            with tarfile.open(archive) as tar:
                # Refuses members that would land outside the directory.
                tar.extractall(SOURCE_DIR, filter='data')
        except (tarfile.TarError, OSError) as e:
            raise Failure('bad_source', 'the source tarball cannot be unpacked: %s' % e, EXIT_FAILED)

        found = []
        for directory, subdirectories, files in os.walk(SOURCE_DIR):
            subdirectories.sort()
            if 'package.xml' not in files:
                continue
            try:
                root = ElementTree.parse(os.path.join(directory, 'package.xml')).getroot()
            except ElementTree.ParseError:
                continue
            if (root.findtext('name') or '').strip() == self.package:
                found.append((directory, (root.findtext('version') or '').strip()))
        if len(found) != 1:
            raise Failure('bad_source', 'the source holds %d packages named %s' % (len(found), self.package),
                          EXIT_FAILED)
        package_dir, self.version = found[0]
        if not re.match(r'^[0-9][0-9A-Za-z.+~]*$', self.version):
            raise Failure('bad_source', 'version %r cannot be a package version' % self.version, EXIT_FAILED)
        for name in ('debian', 'rpm'):
            if os.path.exists(os.path.join(package_dir, name)):
                raise Failure('bad_source', 'the package has a %s directory of its own' % name, EXIT_FAILED)
        print('Found %s %s in %s' % (self.package, self.version, os.path.relpath(package_dir, SOURCE_DIR)))

        os.makedirs(BUILD_DIR)
        self.tree = os.path.join(BUILD_DIR, '%s-%s' % (self.package_name, self.version))
        shutil.copytree(package_dir, self.tree, symlinks=True)
        self.archive_tree()

    def tar_tree(self, target):
        """
        Make the upstream tarball from the tree, before anything is added.

        Made the same way every time, so the same source gives the same
        tarball: sorted, owned by root, and compressed without a time.
        """
        code = run(None, cwd=BUILD_DIR, env=self.env, shell_string=(
            'tar --sort=name --owner=0 --group=0 --numeric-owner -cf - "%s" | gzip -n > "%s"'
            % (os.path.basename(self.tree), target)))
        if code != 0:
            raise Failure('bad_source', 'the upstream tarball could not be made', EXIT_FAILED)

    def update_system(self):
        """Apply pending updates, so the result does not depend on the image's age."""
        for command in self.update_commands:
            if retry(3, command, env=self.env) != 0:
                raise Failure('update_failed', 'the system could not be brought up to date', EXIT_INFRASTRUCTURE)

    def fetch_rules(self):
        os.makedirs(ROSDEP_SOURCES_DIR, exist_ok=True)
        for name in os.listdir(ROSDEP_SOURCES_DIR):
            os.remove(os.path.join(ROSDEP_SOURCES_DIR, name))
        shutil.rmtree(ROSDEP_CACHE_DIR, ignore_errors=True)
        with open(os.path.join(ROSDEP_SOURCES_DIR, '20-default.list'), 'w') as f:
            for rule in self.rules:
                f.write('yaml %s/%s\n' % (self.rosdistro_url, rule))
        if retry(3, ['rosdep', 'update', '--rosdistro', self.rosdistro], env=self.env) != 0:
            raise Failure('rosdep_update_failed', 'the rosdep rules could not be fetched', EXIT_INFRASTRUCTURE)

        # What was fetched is what every dependency of this build is
        # resolved from. It is kept with the build, so that the build can
        # be explained, and repeated, after the rules have moved on.
        for directory, subdirectories, files in os.walk(ROSDEP_CACHE_DIR):
            subdirectories.sort()
            for name in sorted(files):
                path = os.path.join(directory, name)
                self.rosdep_cache.append({
                    'name': os.path.relpath(path, ROSDEP_CACHE_DIR),
                    'sha256': sha256_of(path),
                })
        code = run(None, env=self.env, shell_string=(
            'tar --sort=name --owner=0 --group=0 --numeric-owner --mtime=@0 -C "%s" -cf - . | gzip -n > "%s"'
            % (ROSDEP_CACHE_DIR, os.path.join(OUT_DIR, 'rosdep-cache.tar.gz'))))
        if code != 0 or not self.rosdep_cache:
            raise Failure('rosdep_update_failed', 'the fetched rosdep rules could not be kept', EXIT_FAILED)
        print('Kept %d files of rosdep rules.' % len(self.rosdep_cache))

    def record_installed(self):
        """Keep the list of what the build ran against."""
        output = output_of(self.list_installed_command)
        with open(os.path.join(OUT_DIR, 'installed-packages.txt'), 'w') as f:
            f.write('\n'.join(sorted(output.splitlines())) + '\n')
        print('Recorded %d installed packages.' % len(output.splitlines()))

    def collect(self):
        packages = os.path.join(OUT_DIR, 'packages')
        os.makedirs(packages, exist_ok=True)
        paths = self.package_files()
        for path in paths:
            shutil.copy(path, packages)
            self.artifacts.append({
                'name': 'packages/' + os.path.basename(path),
                'bytes': os.path.getsize(path),
                'sha256': sha256_of(path),
            })
            print('%10d  %s' % (os.path.getsize(path), os.path.basename(path)))
        names = [os.path.basename(path) for path in paths]
        if not any(self.is_binary_package(name) for name in names):
            raise Failure('build_failed', 'the build left no binary package', EXIT_FAILED)
        if not any(self.is_source_package(name) for name in names):
            raise Failure('build_failed', 'the build left no source package', EXIT_FAILED)
        for path in paths:
            if self.is_binary_package(os.path.basename(path)):
                self.describe(path)

        if not self.test:
            return
        self.tests = collect_test_results(TEST_RESULTS_DIR, self.package)
        print('\nTests: %(total)d run, %(failed)d failed, %(errors)d errors, %(skipped)d skipped' % self.tests)
        if not self.tests['reports']:
            self.warnings.append('the tests left no results')
        if self.tests['failed'] or self.tests['errors']:
            raise Failure('tests_failed', '%d tests failed' % (self.tests['failed'] + self.tests['errors']),
                          EXIT_FAILED)

    # -- the whole job -----------------------------------------------

    def main(self):
        status, message, code = 'success', '', EXIT_OK
        try:
            self.stage('Unpack the source', self.unpack)
            self.stage('Bring the system up to date', self.update_system)
            self.stage('Fetch the rosdep rules', self.fetch_rules)
            self.stage('Generate the packaging', self.generate)
            self.stage('Install build dependencies', self.install_build_dependencies)
            self.stage('Build', self.build)
            self.stage('Collect', self.collect)
        except Failure as failure:
            status, message, code = failure.status, str(failure), failure.code
        self.write_results(status, message)
        section('Result: %s%s' % (status, ' (%s)' % message if message else ''))
        return code

    def write_results(self, status, message):
        os.makedirs(OUT_DIR, exist_ok=True)
        try:
            self.tools = self.tool_versions()
        except Exception as e:  # noqa: B902
            self.warnings.append('the versions of the packaging tools could not be read: %s' % e)
        results = {
            'schema_version': 1,
            'job': 'package_build',
            'status': status,
            'message': message,
            'package': self.package,
            'version': self.version,
            'rosdistro': self.rosdistro,
            'format': self.format,
            'package_name': self.package_name,
            'revision': int(self.revision),
            # What the dependencies were resolved from, and with what.
            'rosdep': {
                'rosdistro_url': self.rosdistro_url,
                'rules': self.rules,
                'skip_keys': self.skip_keys,
                'fetched': self.rosdep_cache,
            },
            'tools': self.tools,
            'stages': self.stages,
            'artifacts': self.artifacts,
            'tests': self.tests,
            'warnings': self.warnings,
        }
        with open(os.path.join(OUT_DIR, 'results.json'), 'w') as f:
            json.dump(results, f, indent=1)
            f.write('\n')


class DebJob(Job):
    """Debian packages, with the packaging written by dyndeb."""

    format = 'deb'
    update_commands = (['apt-get', 'update'], ['apt-get', '-y', 'dist-upgrade'])
    list_installed_command = ['dpkg-query', '-W', '-f', '${Package} ${Version} ${Architecture}\n']
    # What dpkg-buildpackage leaves beside the source tree.
    patterns = ('*.deb', '*.ddeb', '*.dsc', '*.orig.tar.*', '*.debian.tar.*', '*.buildinfo', '*.changes')

    def __init__(self, params):
        super().__init__(params)
        if self.skip_keys:
            raise Failure('bad_parameters', '"skip_keys" is not supported for Debian packages yet', EXIT_FAILED)

    def tool_versions(self):
        return {
            'dyndeb': output_of([sys.executable, '-c', 'import dyndeb; print(dyndeb.__version__)']),
            'debhelper': output_of(['dpkg-query', '-W', '-f', '${Version}', 'debhelper']),
            'dpkg-dev': output_of(['dpkg-query', '-W', '-f', '${Version}', 'dpkg-dev']),
        }

    def archive_tree(self):
        self.tar_tree(os.path.join(BUILD_DIR, '%s_%s.orig.tar.gz' % (self.package_name, self.version)))

    def generate(self):
        unresolved = []

        def watch(line):
            # The generator lists each key it could not resolve, indented.
            if listing[0] and line.startswith('  '):
                unresolved.append(line.strip())
            else:
                listing[0] = 'do not resolve to a package' in line

        listing = [False]
        code = run(['dyndeb-generate', '--rosdistro', self.rosdistro, '--revision', self.revision, self.tree],
                   env=self.env, watch=watch)
        if code == 3:
            self.warnings.extend(unresolved)
            raise Failure('unresolved_dependencies', 'some rosdep keys do not resolve on this target', EXIT_FAILED)
        if code != 0:
            raise Failure('packaging_failed', 'the packaging could not be generated', EXIT_FAILED)
        for name in ('control', 'rules', 'changelog'):
            print('\n----- debian/%s' % name)
            with open(os.path.join(self.tree, 'debian', name)) as f:
                sys.stdout.write(f.read())
        sys.stdout.flush()

    def install_build_dependencies(self):
        command = ['apt-get', 'build-dep', '-y', '--no-install-recommends']
        if not self.test:
            command += ['-P', 'nocheck']
        command.append('./')
        unknown = []

        def watch(line):
            if re.search(r'Unable to locate package|has no installation candidate|'
                         r'but it is not installable|Unable to correct problems', line):
                unknown.append(line.strip())

        for attempt in (1, 2):
            if run(command, cwd=self.tree, env=self.env, watch=watch) == 0:
                break
            if unknown:
                self.warnings.extend(sorted(set(unknown)))
                raise Failure('unknown_packages',
                              'the packaging names a build dependency this target does not have', EXIT_FAILED)
            if attempt == 2:
                raise Failure('install_failed', 'the build dependencies could not be installed',
                              EXIT_INFRASTRUCTURE)
            print('-- failed; trying again in 20 seconds', flush=True)
            time.sleep(20)
        self.record_installed()

    def build(self):
        env = self.build_env()
        # Where the generated rules leave the test results.
        env['ROS_TEST_RESULTS_DIR'] = TEST_RESULTS_DIR
        command = ['dpkg-buildpackage', '-us', '-uc']
        if not self.test:
            env['DEB_BUILD_OPTIONS'] = (env.get('DEB_BUILD_OPTIONS', '') + ' nocheck').strip()
            command += ['-Pnocheck']
        unresolved = []

        def watch(line):
            # dh_rosdep lists each key it could not resolve, indented.
            if listing[0] and line.startswith('  '):
                unresolved.append(line.strip())
            else:
                listing[0] = line.startswith('dh_rosdep: these rosdep keys')

        listing = [False]
        code = run(command, cwd=self.tree, env=env, watch=watch)
        if code != 0:
            if unresolved:
                self.warnings.extend(unresolved)
                raise Failure('unresolved_dependencies',
                              'some install-time rosdep keys do not resolve on this target', EXIT_FAILED)
            raise Failure('build_failed', 'the package build failed', EXIT_FAILED)

    def package_files(self):
        return sorted({path for pattern in self.patterns for path in glob.glob(os.path.join(BUILD_DIR, pattern))})

    def is_binary_package(self, name):
        return name.endswith('.deb')

    def is_source_package(self, name):
        return name.endswith('.dsc')

    def describe(self, path):
        run(['dpkg-deb', '--info', path])


class RpmJob(Job):
    """
    RPM packages, with the spec file written by bloom.

    This is how build.ros2.org builds for RHEL 10: the spec comes from the
    templates of bloom's dynamic RPM generator, and the macros in the
    bloom-rpm-macros package resolve the dependencies while rpmbuild runs.
    """

    format = 'rpm'
    update_commands = (['dnf', '-y', 'upgrade'],)
    list_installed_command = ['rpm', '-qa', '--qf', '%{NAME} %{VERSION}-%{RELEASE} %{ARCH}\n']
    # The script behind bloom's macros, which answers what a package.xml
    # depends on.
    BLOOM_DEPS = '/usr/lib/rpm/bloom-deps.py'

    def __init__(self, params):
        super().__init__(params)
        self.topdir = os.path.join(WORK, 'rpmbuild')
        self.spec = os.path.join(self.topdir, 'SPECS', self.package_name + '.spec')

    def tool_versions(self):
        return {
            'bloom': output_of([sys.executable, '-c',
                                'import importlib.metadata as m; print(m.version("bloom"))']),
            'bloom-rpm-macros': output_of(['rpm', '-q', '--qf', '%{VERSION}-%{RELEASE}', 'bloom-rpm-macros']),
            'rpm-build': output_of(['rpm', '-q', '--qf', '%{VERSION}-%{RELEASE}', 'rpm-build']),
        }

    def rpmbuild(self, *arguments):
        command = ['rpmbuild', '--define', '_topdir ' + self.topdir]
        if not self.test:
            command += ['--without', 'tests']
        if self.skip_keys:
            command += ['--define', '_bloom_skip_keys ' + ' '.join(self.skip_keys)]
        return command + list(arguments)

    def archive_tree(self):
        for name in ('SOURCES', 'SPECS'):
            os.makedirs(os.path.join(self.topdir, name))
        self.tar_tree(os.path.join(self.topdir, 'SOURCES', '%s-%s.tar.gz' % (self.package_name, self.version)))

    def generate(self):
        # bloom writes the spec into an rpm directory beside package.xml.
        # It works on a copy, so that the tree stays as upstream has it.
        scratch = os.path.join(WORK, 'spec')
        shutil.copytree(self.tree, scratch, symlinks=True)
        code = run([sys.executable, '-c', RENDER_SPEC, scratch, self.rosdistro, self.revision], env=self.env)
        rendered = os.path.join(scratch, 'rpm', 'template.spec')
        if code != 0 or not os.path.isfile(rendered):
            raise Failure('packaging_failed', 'the spec file could not be generated', EXIT_FAILED)
        shutil.copy(rendered, self.spec)
        print('\n----- %s' % os.path.basename(self.spec))
        with open(self.spec) as f:
            sys.stdout.write(f.read())
        sys.stdout.flush()

        # The spec names no dependencies: they are resolved while rpmbuild
        # runs, the last of them after the build. They are resolved here
        # as well, and thrown away, so that a key with no package is found
        # before anything is built.
        command = [self.BLOOM_DEPS, os.path.join(self.tree, 'package.xml'), self.package_name,
                   '--requires-build', '--requires', '--requires-devel', '--resolve-groups']
        if self.test:
            command.append('--requires-check')
        if self.skip_keys:
            command += ['--skip-keys'] + self.skip_keys
        last = []
        if run(command, env=self.env, watch=lambda line: last.append(line) if line.strip() else None) != 0:
            if last:
                self.warnings.append(last[-1].strip())
            raise Failure('unresolved_dependencies', 'some rosdep keys do not resolve on this target', EXIT_FAILED)

    def builddep(self, what):
        unknown = []

        def watch(line):
            if re.search(r'No match for argument|No matching package to install|Not all dependencies satisfied|'
                         r'nothing provides', line):
                unknown.append(line.strip())

        command = ['dnf', 'builddep', '-y', '--define', '_topdir ' + self.topdir]
        if not self.test:
            command += ['--define', '_without_tests 1']
        for attempt in (1, 2):
            if run(command + [what], env=self.env, watch=watch) == 0:
                return
            if unknown:
                self.warnings.extend(sorted(set(unknown)))
                raise Failure('unknown_packages',
                              'the packaging names a build dependency this target does not have', EXIT_FAILED)
            if attempt == 2:
                raise Failure('install_failed', 'the build dependencies could not be installed',
                              EXIT_INFRASTRUCTURE)
            print('-- failed; trying again in 20 seconds', flush=True)
            time.sleep(20)

    def install_build_dependencies(self):
        # First what the spec names outright, which includes the macros
        # that work out the rest.
        self.builddep(self.spec)
        # Then what the macros say. rpmbuild ends with 11 when it has
        # found dependencies that are not installed, and leaves a package
        # that names them. More than one round is possible, because
        # installing some can let it find more.
        env = self.build_env()
        for _ in range(5):
            code = run(self.rpmbuild('-br', self.spec), env=env)
            if code == 0:
                break
            found = glob.glob(os.path.join(self.topdir, 'SRPMS', '*.buildreqs.nosrc.rpm'))
            if code != 11 or not found:
                raise Failure('packaging_failed', 'the build dependencies could not be worked out', EXIT_FAILED)
            for path in found:
                self.builddep(path)
                os.remove(path)
        else:
            raise Failure('packaging_failed', 'the build dependencies did not settle', EXIT_FAILED)
        for path in glob.glob(os.path.join(self.topdir, 'SRPMS', '*.rpm')):
            os.remove(path)
        self.record_installed()

    def build(self):
        env = self.build_env()
        if self.test:
            # bloom's spec runs pytest with no options. This is how pytest
            # is told to leave its results where they can be collected.
            os.makedirs(TEST_RESULTS_DIR, exist_ok=True)
            env['PYTEST_ADDOPTS'] = '--junit-xml=%s -o junit_suite_name=%s' % (
                os.path.join(TEST_RESULTS_DIR, 'pytest.xml'), self.package)
        if run(self.rpmbuild('-ba', self.spec), env=env) != 0:
            raise Failure('build_failed', 'the package build failed', EXIT_FAILED)

    def package_files(self):
        return sorted(glob.glob(os.path.join(self.topdir, 'RPMS', '*', '*.rpm'))
                      + glob.glob(os.path.join(self.topdir, 'SRPMS', '*.src.rpm')))

    def is_binary_package(self, name):
        return name.endswith('.rpm') and not name.endswith('.src.rpm')

    def is_source_package(self, name):
        return name.endswith('.src.rpm')

    def describe(self, path):
        run(['rpm', '-qp', '--qf',
             '%{NAME} %{VERSION}-%{RELEASE} %{ARCH}\\n[  requires %{REQUIRENEVRS}\\n][  provides %{PROVIDENEVRS}\\n]',
             path])


